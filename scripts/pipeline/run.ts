/**
 * The data pipeline (PRD §6.3): fetch → normalize → overrides → validate, for every country in
 * data/overrides/countries/.
 *
 * Reads   data/overrides/countries/<id>.json   the curated file: lane, states, offices, ids, patches
 * Writes  data/raw/<id>/*.json                 the Wikidata and Commons responses
 *         data/merged/<id>.json                the country file the site is built from
 *         artifacts/data-review/pipeline.md    what came from where, and what could not be used
 *         artifacts/data-review/completeness.md  which lanes are complete (D10)
 *
 * Fails if any merged file is invalid.
 *
 * Run: pnpm data:pipeline            (add --refresh to query Wikidata again; name countries to limit the run)
 */
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { validateCountryFile } from "../../src/lib/data/validate";
import { HEAD_OF_GOVERNMENT_FROM, OFFICES } from "../offices";
import { gaps, type CoverageException, type Gap } from "./complete";
import { fetchCountry } from "./fetch";
import { normalize, type AddedTerm, type Curated, type Result } from "./normalize";

const root = process.cwd();
const args = process.argv.slice(2);
const refresh = args.includes("--refresh");
const only = args.filter((a) => !a.startsWith("--"));
const json = async <T>(file: string) => JSON.parse(await readFile(path.join(root, file), "utf8")) as T;
const NOW = new Date().getUTCFullYear();

export async function buildCountry(curated: Curated, opts: { refresh: boolean; manualFa: Record<string, string>; addedTerms: AddedTerm[] }): Promise<Result> {
  const id = curated.country.id;
  const hog = OFFICES[id] ?? [];
  const raw = await fetchCountry(
    path.join(root, "data/raw", id),
    curated.states.flatMap((s) => (s.wikidata ? [s.wikidata] : [])),
    [...new Set([...hog, ...curated.offices.map((o) => o.office)])],
    curated.persons.map((p) => p.wikidata),
    [...new Set(curated.flags.map((f) => f.file))],
    opts.refresh,
  );
  return normalize(raw, { curated, hogOffices: hog, hogFrom: HEAD_OF_GOVERNMENT_FROM, manualFa: opts.manualFa, addedTerms: opts.addedTerms });
}

async function main() {
  const files = (await readdir(path.join(root, "data/overrides/countries"))).filter((f) => f.endsWith(".json")).sort();
  const manualFa = (await json<{ names: Record<string, string> }>("data/overrides/persian-names.json")).names;
  const addedTerms = (await json<{ terms: AddedTerm[] }>("data/overrides/heads-of-government.json")).terms;
  const exceptions = (await json<{ exceptions: CoverageException[] }>("data/policy/coverage-exceptions.json")).exceptions;
  await mkdir(path.join(root, "data/merged"), { recursive: true });

  const done: { id: string; result: Result; issues: string[]; open: Gap[] }[] = [];
  for (const name of files) {
    const curated = await json<Curated>(`data/overrides/countries/${name}`);
    const id = curated.country.id;
    if (only.length && !only.includes(id)) continue;
    const result = await buildCountry(curated, { refresh, manualFa, addedTerms });
    await writeFile(path.join(root, "data/merged", `${id}.json`), JSON.stringify(result.file, null, 2) + "\n");
    const check = validateCountryFile(result.file);
    const issues = check.ok ? [] : check.issues.map((i) => `${i.path}: ${i.message}`);
    const open = gaps(result.file, 1800, NOW, exceptions);
    done.push({ id, result, issues, open });
    console.log(`${id.padEnd(8)} ${String(result.file.terms.length).padStart(4)} terms (${result.origin.wikidata} from Wikidata, ${result.origin.curated} curated), ${issues.length} validation issues, ${open.length} gaps`);
  }
  if (only.length) return;

  const out = path.join(root, "artifacts/data-review");
  const count = (r: Result, from: string) => [...r.persian.values()].filter((v) => v === from).length;
  const pipeline = [
    "# Pipeline run",
    "",
    "Generated by `pnpm data:pipeline`. The site is built from `data/merged/`, which this run writes from Wikidata (`data/raw/`) and the curated files (`data/overrides/`).",
    "",
    "## Where the office terms come from",
    "",
    "| Country | Terms | From Wikidata | Curated | Share from Wikidata |",
    "| --- | ---: | ---: | ---: | ---: |",
    ...done.map(({ id, result: r }) => `| ${id} | ${r.file.terms.length} | ${r.origin.wikidata} | ${r.origin.curated} | ${Math.round((100 * r.origin.wikidata) / r.file.terms.length)}% |`),
    "",
    "Curated terms are those Wikidata lacks, dates differently from the cited source, or cannot express (party leaders under R4, Iran's presidents of 1980–1989 under R8, one person under two titles under R1). Each carries its own source.",
    "",
    "## Where the Persian names of people come from",
    "",
    "| Country | People | fa.wikipedia title | Wikidata label | persian-names.json | Kept by an override |",
    "| --- | ---: | ---: | ---: | ---: | ---: |",
    ...done.map(({ id, result: r }) => `| ${id} | ${r.file.persons.length} | ${count(r, "fa.wikipedia")} | ${count(r, "Wikidata label")} | ${count(r, "persian-names.json")} | ${count(r, "override")} |`),
    "",
    "## What the pipeline did not use",
    "",
    "| Country | Kind | Count |",
    "| --- | --- | ---: |",
    ...done.flatMap(({ id, result: r }) => [...Map.groupBy(r.notes, (n) => n.kind)].sort().map(([k, v]) => `| ${id} | ${k} | ${v.length} |`)),
    "",
    ...done.flatMap(({ id, result: r }) => {
      const shown = r.notes.filter((n) => n.kind.startsWith("R3") || n.kind.startsWith("flag") || n.kind.startsWith("term with no title"));
      return shown.length ? [`**${id}**`, "", ...shown.map((n) => `- ${n.kind}: ${n.record}${n.detail ? ` (${n.detail})` : ""}`), ""] : [];
    }),
  ];
  await writeFile(path.join(out, "pipeline.md"), pipeline.join("\n"));

  const complete = [
    "# Complete lanes, 1800 – today",
    "",
    "Generated by `pnpm data:pipeline`. A lane is complete when every year has a lane period and every year of a state has a head of state or leader, a head of government, a capital, a system and a flag (data phase proposal, D10). Where no flag is documented, the country's file says so with a “no documented flag” record (PRD §7.7). A year that truly had none is closed by an entry in `data/policy/coverage-exceptions.json` that names a source.",
    "",
    "| Country | Complete | Open gaps | Years of state without a head of state | … without a head of government | … without a flag | Years recorded as “no documented flag” |",
    "| --- | --- | ---: | ---: | ---: | ---: | ---: |",
    ...done.map(({ id, open, result }) => {
      const n = (need: string) => open.filter((g) => g.need === need).reduce((sum, g) => sum + g.end - g.start + 1, 0);
      const none = (result.file.noFlag ?? []).reduce((sum, f) => sum + Math.max(0, (f.end ?? NOW + 1) - Math.max(f.start, 1800)), 0);
      return `| ${id} | ${open.length === 0 ? "**yes**" : "no"} | ${open.length} | ${n("head of state")} | ${n("head of government")} | ${n("flag")} | ${none} |`;
    }),
    "",
    `${done.filter((d) => d.open.length === 0).length} of ${done.length} countries are complete. ${exceptions.length} recorded exceptions.`,
    "",
    "## Open gaps",
    "",
    "| Country | State | Missing | Years |",
    "| --- | --- | --- | --- |",
    ...done.flatMap(({ id, open }) => open.map((g) => `| ${id} | ${g.state ?? "(lane)"} | ${g.need} | ${g.start === g.end ? g.start : `${g.start}–${g.end}`} |`)),
    "",
  ];
  await writeFile(path.join(out, "completeness.md"), complete.join("\n"));

  const bad = done.filter((d) => d.issues.length);
  for (const d of bad) console.error(`✗ ${d.id}\n${d.issues.map((i) => `    ${i}`).join("\n")}`);
  if (bad.length) process.exit(1);
}

if (process.argv[1]?.endsWith("run.ts")) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
